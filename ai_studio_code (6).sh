# 1. Download and extract telesell-full-source.zip or use the workspace root:
cd telesell-saas

# 2. Initialize git repository
git init
git branch -M main

# 3. Stage all files
git add .

# 4. Commit code
git commit -m "feat: complete TeleSell source code with Android native APK setup"

# 5. Link your GitHub remote
git remote add origin https://github.com/<YOUR_GITHUB_USERNAME>/<YOUR_REPOSITORY_NAME>.git

# 6. Push to GitHub
git push -u origin main